from django.db import models
from apps.kpi.models.kpi_definition import KPIDefinition
from apps.imports.models.import_batch import ImportBatch
from apps.imports.models.staged_data import ImportStagedRow
from apps.imports.models.template import UploadTemplate
from apps.organization.models import Circle


class KPICalculatedOutput(models.Model):
    """
    Persisted row-level calculated output generated by dynamic formula execution.
    Preserves original uploaded Excel records untouched while making the derived
    logical columns available to downstream views and cockpit reporting.
    """
    class Status(models.TextChoices):
        SUCCESS = "SUCCESS", "Success"
        PENDING_DATA = "PENDING_DATA", "Pending Data"
        INVALID_INPUT = "INVALID_INPUT", "Invalid Input"
        MISSING_COLUMN = "MISSING_COLUMN", "Missing Column"
        DIV_ZERO = "DIV_ZERO", "Division by Zero"
        ERROR = "ERROR", "Calculation Error"

    kpi = models.ForeignKey(
        KPIDefinition,
        on_delete=models.CASCADE,
        related_name="calculated_outputs"
    )
    rule_id = models.CharField(max_length=100, blank=True, default="", db_index=True)
    formula_name = models.CharField(max_length=200, blank=True, default="")
    batch = models.ForeignKey(
        ImportBatch,
        on_delete=models.CASCADE,
        related_name="calculated_outputs"
    )
    staged_row = models.ForeignKey(
        ImportStagedRow,
        on_delete=models.CASCADE,
        related_name="calculated_outputs"
    )
    row_index = models.PositiveIntegerField(help_text="Excel row index matching staged row")
    template = models.ForeignKey(
        UploadTemplate,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="calculated_outputs"
    )
    reporting_period = models.ForeignKey(
        "dashboard.ReportingPeriod",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        db_constraint=False
    )
    reporting_date = models.DateField(null=True, blank=True, db_index=True)
    circle = models.ForeignKey(
        Circle,
        on_delete=models.SET_NULL,
        null=True,
        blank=True
    )
    
    input_column = models.CharField(max_length=150, help_text="Source Excel column name")
    input_unit = models.CharField(max_length=50, blank=True, default="")
    input_values = models.JSONField(default=dict, blank=True, help_text="Snapshot of raw input values used")
    
    formula_expression = models.TextField(blank=True, default="")
    constants_applied = models.JSONField(default=dict, blank=True)
    
    output_column_name = models.CharField(max_length=150, db_index=True, help_text="Calculated output column name, e.g. 'Uptime'")
    output_unit = models.CharField(max_length=50, blank=True, default="%", help_text="Calculated unit, e.g. '%'")
    calculated_value = models.DecimalField(max_digits=18, decimal_places=4, null=True, blank=True)
    decimal_precision = models.PositiveSmallIntegerField(default=2)
    
    status = models.CharField(max_length=30, choices=Status.choices, default=Status.SUCCESS, db_index=True)
    error_message = models.TextField(blank=True, default="")
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = "kpi_kpicalculatedoutput"
        ordering = ["batch", "row_index", "output_column_name"]
        unique_together = ("kpi", "staged_row", "output_column_name")
        indexes = [
            models.Index(fields=["batch", "row_index"]),
            models.Index(fields=["kpi", "reporting_date"]),
        ]
        verbose_name = "KPI Calculated Output"
        verbose_name_plural = "KPI Calculated Outputs"

    def __str__(self):
        return f"{self.kpi.code} Row #{self.row_index}: {self.output_column_name} = {self.calculated_value} {self.output_unit} [{self.status}]"
